"""Phase 3.3-RESEARCH -- controlled pilot: prompt-format and generation-budget variants
against the reasoning bottleneck identified by directly analyzing the frozen 240-record
dataset (see PHASE3_RESEARCH_IMPROVEMENT_PLAN.md).

READ-ONLY WITH RESPECT TO THE FROZEN BASELINE
--------------------------------------------------------------------------------
This script imports and reuses `runner.py`, `messages.py`, `gold_evidence_runner.py`,
`campaign_runner.py`'s ingestion helper, and `provider.py` UNMODIFIED. It writes its own
NEW results file under `phase3/experiments/research_variant/results/` and never touches
`phase3/experiments/results/canonical_store/` (the frozen 120x2 dataset and its
manifests). V1 (`runner.py::run_agent_task`) is not called by this script in its literal
form for conditions B/C (a custom, structurally-identical variant loop is used so that
system prompt and max_tokens can vary per call without re-ingesting per variant) -- but
every primitive it calls (`generate_with_retries`, `render_messages`,
`build_agent_visible_context`, the real `RealMem0Adapter`) is the exact same one V1 uses.

TASK SELECTION
--------------------------------------------------------------------------------
15 real task_ids, deterministically chosen as the first 15 (by task_id sort order) LoCoMo
MEM0-foundation records already present in the frozen 240-record dataset -- i.e. this is
NOT a fresh resample; every task here has an existing, recorded frozen V1 answer we can
sanity-check the BASELINE variant against. Real question/answer/evidence pulled directly
from data/processed/locomo/{task_records,memory_records}.jsonl.

VARIANTS (see module docstring in the improvement plan for the hypothesis behind each)
--------------------------------------------------------------------------------
- BASELINE       : DEFAULT_SYSTEM_PROMPT (messages.py, unmodified), max_tokens=64
                    (exactly what the frozen 120x2 campaign used: campaign_formal_runner.py
                    calls clean_baseline_generation_config(n_ctx=4096, max_tokens=64)).
- V_FORMAT        : a terser, gold-answer-shaped system prompt, max_tokens=64 (isolates
                    prompt-wording effect alone).
- V_BUDGET        : DEFAULT_SYSTEM_PROMPT, max_tokens=160 (isolates truncation effect
                    alone -- real sampled Condition-B answers were observed cut off
                    mid-sentence at the 64-token budget).
- V_FORMAT_BUDGET : both combined.

Retrieval/selection is run ONCE per task (top_k=5, identical to V1's provisional
`select_from_retrieved` policy) and REUSED across all four variants for Condition C --
retrieval is deterministic given the same ingested pool, so re-running it per variant
would be wasted, redundant foundation calls, not a different experiment.
"""

from __future__ import annotations

import json
import sys
import time
from pathlib import Path
from typing import Any, List, Mapping, Optional, Sequence, Tuple

_REPO_ROOT = Path(__file__).resolve().parents[3]
if str(_REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(_REPO_ROOT))

from phase3.evaluation.agent.conditions import CONDITION_GOLD_EVIDENCE, CONDITION_RETRIEVED_MEMORY, build_agent_visible_context
from phase3.evaluation.agent.normalized_correctness import evaluate_answer_correctness_normalized
from phase3.evaluation.agent.outcomes import (
    EXECUTION_STATUS_ERROR,
    EXECUTION_STATUS_SUCCESS,
    AgentExecutionResult,
    evaluate_answer_correctness,
)
from phase3.evaluation.agent_runtime.messages import DEFAULT_SYSTEM_PROMPT, render_messages
from phase3.evaluation.agent_runtime.runner import (
    RunConfiguration,
    _extract_content_text,
    _extract_memory_id,
    generate_with_retries,
    select_from_retrieved,
)
from phase3.evaluation.foundations.adapter import FOUNDATION_AVAILABLE, FOUNDATION_PARTIAL
from phase3.evaluation.llm.provider import (
    LlamaServerEndpoint,
    LlamaServerProvider,
    clean_baseline_generation_config,
)

_DATA_ROOT = _REPO_ROOT / "data" / "processed"
_OUT_DIR = Path(__file__).resolve().parent / "results"
_OUT_DIR.mkdir(parents=True, exist_ok=True)

# The exact 15 task_ids used: first 15 by task_id sort order among MEM0-foundation
# records in the frozen 240-record dataset. Fixed here, verbatim, not regenerated by
# this script, so the file itself documents exactly which real tasks were used.
FROZEN_DATASET_PATH = (
    _REPO_ROOT / "phase3" / "experiments" / "results" / "canonical_store" / "dataset_full"
    / "clean_agent_dataset_locomo_120x2.json"
)

N_TASKS = 15

VARIANT_TERSE_SYSTEM_PROMPT = (
    "You are answering a factual question using ONLY the retrieved/provided memory "
    "content. Give ONLY the direct factual answer -- a short phrase or sentence, no "
    "preamble, no hedging, no meta-commentary about what the memories do or do not "
    "contain. If the answer is a date, name, place, or short fact, state just that. "
    "If the memories truly contain nothing relevant, reply exactly: 'Not stated in "
    "the provided memories.'"
)

VARIANTS: Mapping[str, Mapping[str, Any]] = {
    "BASELINE": {"system_prompt": DEFAULT_SYSTEM_PROMPT, "max_tokens": 64},
    "V_FORMAT": {"system_prompt": VARIANT_TERSE_SYSTEM_PROMPT, "max_tokens": 64},
    "V_BUDGET": {"system_prompt": DEFAULT_SYSTEM_PROMPT, "max_tokens": 160},
    "V_FORMAT_BUDGET": {"system_prompt": VARIANT_TERSE_SYSTEM_PROMPT, "max_tokens": 160},
}


def _load_jsonl(path: Path):
    with path.open("r", encoding="utf-8") as f:
        for line in f:
            yield json.loads(line)


def _select_task_ids(n: int) -> List[str]:
    with FROZEN_DATASET_PATH.open("r", encoding="utf-8") as f:
        data = json.load(f)
    mem0_task_ids = sorted({r["task_id"] for r in data if r["foundation"] == "MEM0"})
    return mem0_task_ids[:n]


def _build_task_records(task_ids: Sequence[str]) -> List[Mapping[str, Any]]:
    task_records_by_id = {t["task_id"]: t for t in _load_jsonl(_DATA_ROOT / "locomo" / "task_records.jsonl")}
    memory_by_id = {}
    memory_session = {}
    for row in _load_jsonl(_DATA_ROOT / "locomo" / "memory_records.jsonl"):
        memory_by_id[row["memory_id"]] = row
        memory_session[row["memory_id"]] = (row["conversation_id"], row["session_id"])

    tasks = []
    for tid in task_ids:
        t = task_records_by_id[tid]
        sessions = {memory_session[eid] for eid in t["evidence_memory_ids"]}
        assert len(sessions) == 1, f"task {tid} evidence spans multiple sessions -- unexpected for a frozen-dataset task"
        (conv_id, session_id) = next(iter(sessions))
        tasks.append({
            "task_id": tid,
            "question": t["question"],
            "answer": t["answer"],
            "evidence_memory_ids": t["evidence_memory_ids"],
            "conversation_id": conv_id,
            "session_id": session_id,
        })
    return tasks


def _ingest_pool(conv_id: str, session_id: str):
    for row in _load_jsonl(_DATA_ROOT / "locomo" / "memory_records.jsonl"):
        if row["conversation_id"] == conv_id and row["session_id"] == session_id:
            yield row


def _run_condition_c_all_variants(task, llm_provider, results, log):
    from phase3.evaluation.foundations_real.mem0_real_adapter import RealMem0Adapter

    foundation = RealMem0Adapter()
    init_field = foundation.initialize(
        {"embedding_model": "sentence-transformers/all-MiniLM-L6-v2",
         "collection_name": f"research_variant_{task['task_id']}_mem0"}
    )
    if init_field.availability != FOUNDATION_AVAILABLE:
        log(f"  [C] init failed: {init_field.note}")
        return
    foundation.reset()

    for row in _ingest_pool(task["conversation_id"], task["session_id"]):
        foundation.add_memory(
            memory_id=row["memory_id"],
            content={"text": f"{row['source_role']}: {row['content']}"},
            metadata={"user_id": f"rv-{task['task_id']}", "source_memory_id": row["memory_id"]},
        )

    retrieve_field = foundation.retrieve({"text": task["question"], "user_id": f"rv-{task['task_id']}"}, top_k=5)
    retrieved_ids: Tuple[str, ...] = ()
    memory_items: List[Mapping[str, Any]] = []
    if retrieve_field.availability in (FOUNDATION_AVAILABLE, FOUNDATION_PARTIAL):
        raw_items = retrieve_field.value or []
        retrieved_ids = tuple(mid for mid in (_extract_memory_id(i) for i in raw_items) if mid is not None)
        selected_ids = select_from_retrieved(retrieved_ids, top_k=5)
        for mid in selected_ids:
            inspect_field = foundation.inspect_memory(mid)
            if inspect_field.availability in (FOUNDATION_AVAILABLE, FOUNDATION_PARTIAL):
                memory_items.append({"memory_id": mid, "content": _extract_content_text(inspect_field.value or {})})

    for variant_name, variant_cfg in VARIANTS.items():
        context = build_agent_visible_context(
            condition=CONDITION_RETRIEVED_MEMORY, task_id=task["task_id"], prompt=task["question"],
            memory_items=memory_items,
        )
        messages = render_messages(context, variant_cfg["system_prompt"])
        gen_config = clean_baseline_generation_config(n_ctx=4096, max_tokens=variant_cfg["max_tokens"])
        run_config = RunConfiguration(llm_provider=llm_provider, generation_config=gen_config, system_prompt=variant_cfg["system_prompt"])
        t0 = time.time()
        answer, attempts = generate_with_retries(messages, run_config)
        latency = time.time() - t0

        exec_result = AgentExecutionResult(
            task_id=task["task_id"], condition=CONDITION_RETRIEVED_MEMORY, answer=answer,
            execution_status=EXECUTION_STATUS_SUCCESS if answer is not None else EXECUTION_STATUS_ERROR,
            selected_memory_ids=tuple(item["memory_id"] for item in memory_items), used_memory_ids=None,
            execution_metadata={"attempts": len(attempts)},
        )
        exact = evaluate_answer_correctness(exec_result, task["answer"])
        norm = evaluate_answer_correctness_normalized(exec_result, task["answer"])

        results.setdefault(task["task_id"], {})[f"C_{variant_name}"] = {
            "answer": answer, "latency_sec": latency,
            "exact_status": exact.status, "normalized_status": norm.status,
            "retrieved_count": len(retrieved_ids), "selected_count": len(memory_items),
        }
        log(f"  [C/{variant_name}] norm={norm.status} exact={exact.status} ans={str(answer)[:80]!r}")

    foundation.shutdown()


def _run_condition_b_all_variants(task, llm_provider, results, log):
    memory_by_id = {}
    for row in _load_jsonl(_DATA_ROOT / "locomo" / "memory_records.jsonl"):
        memory_by_id[row["memory_id"]] = row

    evidence_items = [
        {"memory_id": f"evidence-slot-{i+1}", "content": f"{memory_by_id[eid]['source_role']}: {memory_by_id[eid]['content']}"}
        for i, eid in enumerate(task["evidence_memory_ids"])
        if eid in memory_by_id
    ]

    for variant_name, variant_cfg in VARIANTS.items():
        context = build_agent_visible_context(
            condition=CONDITION_GOLD_EVIDENCE, task_id=task["task_id"], prompt=task["question"],
            memory_items=evidence_items,
        )
        messages = render_messages(context, variant_cfg["system_prompt"])
        gen_config = clean_baseline_generation_config(n_ctx=4096, max_tokens=variant_cfg["max_tokens"])
        run_config = RunConfiguration(llm_provider=llm_provider, generation_config=gen_config, system_prompt=variant_cfg["system_prompt"])
        t0 = time.time()
        answer, attempts = generate_with_retries(messages, run_config)
        latency = time.time() - t0

        exec_result = AgentExecutionResult(
            task_id=task["task_id"], condition=CONDITION_GOLD_EVIDENCE, answer=answer,
            execution_status=EXECUTION_STATUS_SUCCESS if answer is not None else EXECUTION_STATUS_ERROR,
            selected_memory_ids=(), used_memory_ids=None, execution_metadata={"attempts": len(attempts)},
        )
        exact = evaluate_answer_correctness(exec_result, task["answer"])
        norm = evaluate_answer_correctness_normalized(exec_result, task["answer"])

        results.setdefault(task["task_id"], {})[f"B_{variant_name}"] = {
            "answer": answer, "latency_sec": latency,
            "exact_status": exact.status, "normalized_status": norm.status,
        }
        log(f"  [B/{variant_name}] norm={norm.status} exact={exact.status} ans={str(answer)[:80]!r}")


def main():
    def log(msg):
        print(msg, flush=True)

    task_ids = _select_task_ids(N_TASKS)
    tasks = _build_task_records(task_ids)
    log(f"Selected {len(tasks)} real task_ids (MEM0, first-by-sort-order in frozen dataset): {task_ids}")

    endpoint = LlamaServerEndpoint()
    llm_provider = LlamaServerProvider(endpoint)
    identity_check = llm_provider.verify_server_identity()
    log(f"Server identity verified: {identity_check}")

    results: Mapping[str, Mapping[str, Any]] = {}
    for i, task in enumerate(tasks):
        log(f"\n=== Task {i+1}/{len(tasks)}: {task['task_id']} — {task['question']!r} (gold={task['answer']!r}) ===")
        _run_condition_b_all_variants(task, llm_provider, results, log)
        _run_condition_c_all_variants(task, llm_provider, results, log)

    out_path = _OUT_DIR / "pilot_prompt_budget_variants_n15_mem0.json"
    with out_path.open("w", encoding="utf-8") as f:
        json.dump({"task_ids": task_ids, "tasks": tasks, "results": results, "variants": {k: v for k, v in VARIANTS.items()}}, f, indent=2, ensure_ascii=False)
    log(f"\nWrote {out_path}")

    # Summary
    log("\n=== SUMMARY (normalized correctness) ===")
    for cond in ("B", "C"):
        for variant_name in VARIANTS:
            key = f"{cond}_{variant_name}"
            n_correct = sum(1 for t in results.values() if t.get(key, {}).get("normalized_status") == "ANSWER_CORRECT")
            n_total = sum(1 for t in results.values() if key in t)
            log(f"  {key}: {n_correct}/{n_total}")


if __name__ == "__main__":
    main()
