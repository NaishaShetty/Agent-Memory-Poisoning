def f(x):
    return f"{x['k']}/{x['n']}" if x and x.get("n") is not None else "n/a"


def pc(x):
    return f"{100 * x['rate']:.1f}%" if x and x.get("rate") is not None else "n/a"


def ci(x):
    return f"[{100 * x['ci95'][0]:.1f}, {100 * x['ci95'][1]:.1f}]" if x and x.get("ci95") else ""


def fp(x):
    return f"{f(x)} ({pc(x)}, CI {ci(x)})"


def pd(p):
    return f"+{p['only_b']}/−{p['only_a']}" if p else ""


def table(rows):
    out = ["| " + " | ".join(rows[0]) + " |", "|" + "---|" * len(rows[0])]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows[1:]]
    return "\n".join(out)


def stored_only():
    """D4 sensitivity: every Gap-3 arm's benign rates recomputed on items that have at least one stored memory."""
    st = json.loads((D7 / "sa7_mem0_stage.json").read_text(encoding="utf-8"))["items"]
    it = L("g3_eval_sa7_items.json")
    has = {k: bool(st.get(f"N|{k}", {}).get("derived")) for k in it}
    arms = list(next(iter(it.values()))["flags"])
    out = {}
    for a in arms:
        row = {}
        for grp, kinds in (("implicit", ("atk_implicit",)), ("ungrounded", UNG), ("grounded", ("ben_ground",))):
            xs = [v for k, v in it.items() if v["kind"] in kinds]
            ys = [v for k, v in it.items() if v["kind"] in kinds and has[k]]
            row[grp] = (sum(v["flags"][a] for v in xs), len(xs), sum(v["flags"][a] for v in ys), len(ys))
        out[a] = row
    return out


