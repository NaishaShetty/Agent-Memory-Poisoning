"""Targeted, logged corrections to `Methodology Draft.docx` (register D1, D6, D8, D10, D13, G3-4).

The Methodology is a cumulative record maintained by incremental scripts, not regenerated by one builder,
so its errors are corrected in place here. Rules: each correction must match exactly once (or already be
applied -- idempotent); nothing historical is deleted except the one stale duplicate bracket (D1), which is
an exact superseded copy of the bracket beside it; every replacement value is read from the authoritative
tables; a log of every change is written to `remediation/logs/methodology_patch_log.json`. The pre-patch
file is preserved by git (and a checkpoint copy outside the repo).
"""
from __future__ import annotations

import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DOC = ROOT / "Methodology Draft.docx"
LOG = ROOT / "remediation" / "logs" / "methodology_patch_log.json"


def _lead() -> str:
    t = json.loads((ROOT / "results" / "tables" / "T7_baselines.json").read_text(encoding="utf-8"))
    l = t["lead_on_own_attacks_over_best_baseline"]
    return (f"lead the strongest published baseline ({l['best_baseline'].replace('_', ' ')}) by "
            f"{l['points']['B13']} (B13) to {l['points']['B17']} (B17) points")


def corrections():
    return [
        ("D1", re.compile(r"\s*\[Round 7, final: four hold-outs were scored once each and 34/41 pre-registered predictions "
                          r"held.*?\(Sections 32\.59-32\.60\)\.\]", re.S), "", None),
        ("D1b", re.compile(r"\(17/20 held\)"), "(17/20 held at that point; superseded by the bracket below)",
         "17/20 held at that point"),
        ("D6", re.compile(r"lead by nearly 39 points"), _lead(), "strongest published baseline"),
        ("D10", re.compile(r"content-only detection provably cannot"), "content-only detection cannot, by construction,",
         "cannot, by construction,"),
        ("G3-4", re.compile(r"(a generalized union of provenance and an embedding-anomaly signal beats every single detector "
                            r"across attack types)(;)"),
         r"\1 [CORRECTION 2026-10-12: that union's hold-out-8 anomaly threshold was set on hold-out 8's own benign "
         r"notes; without that leak it needs per-owner benign calibration, and the shipped dev-fitted signal flags "
         r"80% of hold-out 8's benign notes -- Results Section 15]\2", "CORRECTION 2026-10-12: that union"),
        ("D8", re.compile(r"(is not established from available evidence at the time of this paper and is left as explicit "
                          r"future work rather than characterized speculatively here\.)(?! \[2026-10-12)"),
         r"\1 [2026-10-12: that comparison now exists, from primary sources, in RELATED_WORK_AND_NOVELTY.md; several "
         r"contributions this document once called new are adaptations of prior work.]", "that comparison now exists"),
    ]


MULTI = {"D10"}          # the same overclaim appears in the abstract and in Section 33


def _set_text(p, new: str) -> None:
    runs = p.runs
    if not runs:
        p.add_run(new)
        return
    runs[0].text = new
    for r in runs[1:]:
        r.text = ""


def run() -> dict:
    import docx

    d = docx.Document(str(DOC))
    log = []
    for cid, pat, rep, applied_marker in corrections():
        hits = [p for p in d.paragraphs if pat.search(p.text)]
        if not hits:
            done = applied_marker and any(applied_marker in p.text for p in d.paragraphs)
            log.append({"id": cid, "status": "already applied" if done else "NOT FOUND"})
            if not done and cid != "D1":
                raise SystemExit(f"{cid}: target not found and not already applied")
            continue
        multi = cid in MULTI
        if not multi and (len(hits) != 1 or len(pat.findall(hits[0].text)) != 1):
            raise SystemExit(f"{cid}: expected exactly one match, got {len(hits)} paragraphs")
        for h in hits:
            before = h.text
            m = pat.search(before)
            after = pat.sub(rep, before)
            _set_text(h, after)
            log.append({"id": cid, "status": "applied", "before_excerpt": m.group(0)[:300],
                        "after_excerpt": after[max(0, m.start() - 20):m.start() + 300]})
    # one dated pointer paragraph after the first abstract paragraph (idempotent)
    marker = "REMEDIATION (2026-10-12)"
    if not any(p.text.startswith(marker) for p in d.paragraphs):
        anchor = next(p for p in d.paragraphs if p.text.startswith("How to read this document."))
        new = anchor.insert_paragraph_before("")
        anchor._p.addnext(new._p)                        # move it to just after the anchor
        new.add_run(f"{marker}: an independent pre-submission review led to the corrections marked "
                    "'CORRECTION 2026-10-12' below, two new pre-registered experiments (sleeper activation, "
                    "two-generation propagation) and a separate IEEE manuscript (paper/). The authoritative "
                    "numbers are in results/TABLE_INDEX.md; every review finding has a status in "
                    "REMEDIATION_MASTER_REGISTER.md. Earlier text is otherwise unchanged.")
        log.append({"id": "pointer", "status": "applied"})
    else:
        log.append({"id": "pointer", "status": "already applied"})
    d.save(str(DOC))
    LOG.parent.mkdir(parents=True, exist_ok=True)
    LOG.write_text(json.dumps(log, indent=2, ensure_ascii=False), encoding="utf-8")
    return {"log": log}


if __name__ == "__main__":
    for x in run()["log"]:
        print(x["id"], x["status"])
